echo ""
echo "2. Verbose mode (AOC_DRY_RUN=, AOC_VERBOSE=1):"
echo "   - Expected: Show 'running: command' + actual command output"
echo ""
echo "3. Dry-run mode (AOC_DRY_RUN=1, AOC_VERBOSE=):"
echo "   - Expected: Show 'running: command' but NOT execute command"
